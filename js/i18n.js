/* ============================================================
   LANGUAGE DETECTION
   ============================================================ */
export const SUPPORTED_LANGS = Object.keys(TRANSLATIONS);

/**
 * Detects the user's preferred language from the browser.
 * Falls back to 'en' if the browser language is not supported.
 */
export function detectLang() {
  const candidates = [
    navigator.language,
    ...(navigator.languages || []),
    'en'
  ];
  for (const raw of candidates) {
    if (!raw) continue;
    const short = raw.toLowerCase().split('-')[0];
    if (TRANSLATIONS[short]) return short;
  }
  return 'en';
}

/* ============================================================
   SET LANGUAGE
   ============================================================ */
export function setLang(code) {
  if (TRANSLATIONS[code]) {
    state.currentLang = code;
    document.documentElement.lang = code;
  }
}

/* ============================================================
   TRANSLATION LOOKUP
   ============================================================ */
export function t(key) {
  const dict = TRANSLATIONS[state.currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}
